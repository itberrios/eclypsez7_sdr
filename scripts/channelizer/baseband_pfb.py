# ==============================================================================
# Helper Functions: Quantization, .coe Export, Pipeline, and Audio Metrics
# ==============================================================================
def quantize_and_normalize(coeffs, bits=18):
    """Normalize sum to 1.0 (0 dB DC gain), then quantize to signed fixed-point."""
    c_norm = coeffs / np.sum(coeffs)
    max_val = np.max(np.abs(c_norm))
    scale = (2**(bits - 1) - 1) / max_val
    c_quant = np.round(c_norm * scale) / scale
    return c_quant

def write_coe_file(filename, coeffs):
    """Write float-format .coe file for Vivado FIR Compiler."""
    with open(filename, 'w') as f:
        f.write("; Generated by FM Polyphase Channelizer Simulation\n")
        f.write(f"; Taps: {len(coeffs)}, Quantized: {COEFF_BITS}-bit, Sum: {np.sum(coeffs):.6f}\n")
        f.write("radix=10;\n")
        f.write("coefdata=\n")
        for i, c in enumerate(coeffs):
            sep = ";" if i == len(coeffs) - 1 else ","
            f.write(f"{c:.10f}{sep}\n")
    print(f"Exported {filename} ({len(coeffs)} taps, sum={np.sum(coeffs):.6f})")

def compute_sinad_thd(audio_sig, fs_audio, f_tone=1000.0, n_harmonics=5):
    """ Compute SINAD, THD, and normalized PSD for a demodulated FM audio tone.

        Evaluates audio fidelity over the standard FM broadcast mono audio band
        (20 Hz to 15 kHz) using a Hann-windowed real FFT. Startup and teardown
        transients from the upstream resampling and polyphase filters are trimmed
        before spectral analysis.

        Parameters
        ----------
        audio_sig : np.ndarray
            1D real-valued array of demodulated audio samples.
        fs_audio : float
            Sample rate of `audio_sig` in Hz (e.g., 200e3 for a critically sampled
            200 kHz PFB channel).
        f_tone : float, optional
            Expected frequency of the sinusoidal test tone in Hz (default is 1000.0).
        n_harmonics : int, optional
            Highest harmonic order to include in the THD calculation, summing
            harmonics 2*f_tone through n_harmonics*f_tone (default is 5).

        Returns
        -------
        freqs : np.ndarray
            1D array of positive FFT frequency bins in Hz (0 to fs_audio / 2).
        psd_db : np.ndarray
            Power spectral density in dB, normalized so the peak tone sits at 0 dB.
        sinad_db : float
            Signal-to-Noise-and-Distortion ratio in dB across 20 Hz - 15 kHz:
            10 * log10((P_signal + P_noise_and_distortion) / P_noise_and_distortion).
            Includes broadband noise, spurs, aliasing, and all in-band harmonics.
        thd_db : float
            Total Harmonic Distortion in dB relative to the fundamental:
            10 * log10(P_harmonics / P_signal).
        thd_pct : float
            Total Harmonic Distortion as an RMS amplitude percentage:
            100 * sqrt(P_harmonics / P_signal).

        Notes
        -----
        - A ±2 bin integration window (`bw_bins = 2`) is applied around the
        fundamental and each harmonic to capture the full mainlobe energy of
        the Hann window.
        - Trims 3 ms from the start and 1 ms from the end of `audio_sig`; ensure
        the simulation duration is significantly longer than 4 ms so adequate
        frequency resolution (df) remains.
    """
    # Trim startup/ending filter transients
    trim_start = int(0.003 * fs_audio)
    trim_end = int(0.001 * fs_audio)
    sig = audio_sig[trim_start:-trim_end]
    sig = sig - np.mean(sig)  # Remove DC offset

    N = len(sig)
    win = np.hanning(N)
    spec = np.fft.rfft(sig * win)
    psd = np.abs(spec) ** 2
    freqs = np.fft.rfftfreq(N, d=1.0 / fs_audio)
    df = freqs[1] - freqs[0]

    # Locate fundamental bin (+/- 2 bins for Hann mainlobe)
    fund_bin = int(np.round(f_tone / df))
    bw_bins = 2
    fund_mask = np.zeros(len(psd), dtype=bool)
    fund_mask[max(1, fund_bin - bw_bins):min(len(psd), fund_bin + bw_bins + 1)] = True
    p_signal = np.sum(psd[fund_mask])

    # Locate harmonic bins (2f to n_harmonics*f)
    harm_mask = np.zeros(len(psd), dtype=bool)
    for h in range(2, n_harmonics + 1):
        h_bin = int(np.round((h * f_tone) / df))
        if h_bin + bw_bins < len(psd):
            harm_mask[h_bin - bw_bins:h_bin + bw_bins + 1] = True
    p_harmonics = np.sum(psd[harm_mask])

    # Total noise + distortion within audio band (20 Hz to 15 kHz)
    audio_band_mask = (freqs >= 20.0) & (freqs <= 15000.0)
    nad_mask = audio_band_mask & (~fund_mask)
    p_nad = np.sum(psd[nad_mask])

    sinad_db = 10 * np.log10((p_signal + p_nad) / (p_nad + 1e-20))
    thd_db = 10 * np.log10((p_harmonics + 1e-20) / (p_signal + 1e-20))
    thd_pct = 100.0 * np.sqrt((p_harmonics + 1e-20) / (p_signal + 1e-20))

    psd_db = 10 * np.log10(psd / (np.max(psd) + 1e-20) + 1e-20)
    return freqs, psd_db, sinad_db, thd_db, thd_pct

