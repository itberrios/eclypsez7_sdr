N_taps_per_branch = 12      # 12 taps/branch -> 1536 total prototype taps
COEFF_BITS = 18             # Quantization width (18-bit signed for Xilinx DSP48E1)

f_nco = 24.98e6             # Aligns 97.9 MHz to DC (Bin 0) and odd-100 kHz stations to integer bins

