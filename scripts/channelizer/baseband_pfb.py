# 2. Filter Design, Quantization, and .coe Generation
# ==============================================================================
# --- A. 5/24 Rational Resampler LPF (Designed at fs_int = 614.4 MHz) ---
f_pass_resamp = 10.2e6
f_stop_resamp = 15.4e6
trans_width_resamp = (f_stop_resamp - f_pass_resamp) / (fs_int / 2)
n_taps_resamp, beta_resamp = signal.kaiserord(ripple=75.0, width=trans_width_resamp)
n_taps_resamp = int(np.ceil(n_taps_resamp / D) * D)

h_resamp_ideal = signal.firwin(
    n_taps_resamp,
    cutoff=(f_pass_resamp + f_stop_resamp) / 2,
    window=('kaiser', beta_resamp),
    fs=fs_int
)
h_resamp_ideal /= np.sum(h_resamp_ideal)
h_resamp_q = quantize_and_normalize(h_resamp_ideal, bits=COEFF_BITS)
write_coe_file("resampler_5_24_lpf.coe", h_resamp_q)

# --- B. 128-Point PFB Prototype LPF (Designed at fs_pfb = 25.6 MHz) ---
num_taps_pfb = M * N_taps_per_branch
h_pfb_ideal = signal.firwin(
    num_taps_pfb,
    cutoff=channel_width / 2,   # 100 kHz cutoff
    window=('kaiser', 6.0),
    fs=fs_pfb
)
h_pfb_ideal /= np.sum(h_pfb_ideal)
h_pfb_q = quantize_and_normalize(h_pfb_ideal, bits=COEFF_BITS)
write_coe_file("pfb_128ch_prototype.coe", h_pfb_q)

pfb_taps = h_pfb_q.reshape((N_taps_per_branch, M)).T

# ==============================================================================
# 3. DSP Pipeline Function
# ==============================================================================
def run_channelizer_pipeline(adc_real, t_vec, target_bin, freq_dev_hz):
    """Run Complex DDC -> 5/24 Resampler -> 128-pt PFB -> FM Polar Discriminator."""
    ddc_iq = 2.0 * adc_real * np.exp(1j * 2 * np.pi * f_nco * t_vec)
    pfb_in_iq = signal.resample_poly(ddc_iq, up=L, down=D, window=h_resamp_q * L)

    num_blocks = len(pfb_in_iq) // M
    rf_blocks = pfb_in_iq[:num_blocks * M].reshape((num_blocks, M)).T

    pfb_outputs = np.zeros((M, num_blocks), dtype=np.complex128)
    for k in range(M):
        pfb_outputs[k, :] = signal.lfilter(pfb_taps[k, :], 1.0, rf_blocks[k, :])

    channel_matrix = np.fft.fft(pfb_outputs, n=M, axis=0)
    bb_iq = channel_matrix[target_bin, :]

    phase_diff = bb_iq[1:] * np.conj(bb_iq[:-1])
    demod = np.angle(phase_diff) * (channel_width / (2 * np.pi * freq_dev_hz))
    return pfb_in_iq, bb_iq, demod

